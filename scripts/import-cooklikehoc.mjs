import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, extname, relative, sep } from "node:path";

const sourceRoot = process.argv[2];
const outputPath = process.argv[3] ?? "src/data/report-foods.generated.js";

if (!sourceRoot) {
  throw new Error(
    "Usage: node scripts/import-cooklikehoc.mjs <CookLikeHOC path> [output path]",
  );
}

const categoryMap = {
  主食: "staple",
  早餐: "breakfast",
  汤: "soup",
  饮品: "drink",
  炸品: "snack",
};

const vegetableNames = new Set([
  "薄皮青椒",
  "豆皮毛白菜",
  "海带结",
  "青椒蒸豆米",
  "酸辣包菜",
  "蒜苔炒木耳",
  "小炒脆笋",
  "蒸南瓜",
  "蒸嫩豆腐",
]);

async function collectMarkdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) {
      return collectMarkdownFiles(path);
    }
    return extname(entry.name) === ".md" ? [path] : [];
  }));

  return nested.flat();
}

function nutrientValue(markdown, label) {
  const match = markdown.match(
    new RegExp(`\\|\\s*${label}\\s*\\|\\s*([0-9.]+)`, "i"),
  );
  return match ? Number(match[1]) : null;
}

function sourceUrl(relativePath) {
  const encodedPath = relativePath
    .split(sep)
    .map((segment) => encodeURIComponent(segment))
    .join("/");
  return `https://github.com/Gar-b-age/CookLikeHOC/blob/main/${encodedPath}`;
}

const files = await collectMarkdownFiles(sourceRoot);
const records = [];

for (const file of files) {
  const markdown = await readFile(file, "utf8");
  if (!markdown.includes("## 营养成分")) {
    continue;
  }

  const relativePath = relative(sourceRoot, file);
  const folder = basename(dirname(file));
  const values = {
    kcal: nutrientValue(markdown, "热量"),
    proteinG: nutrientValue(markdown, "蛋白质"),
    fatG: nutrientValue(markdown, "脂肪"),
    carbG: nutrientValue(markdown, "碳水化合物"),
    sodiumMg: nutrientValue(markdown, "钠"),
  };

  if (Object.values(values).some((value) => value === null)) {
    throw new Error(`Incomplete nutrition row: ${relativePath}`);
  }

  const hash = createHash("sha1").update(relativePath).digest("hex").slice(0, 10);
  const name = basename(file, ".md");
  records.push({
    id: `report-${hash}`,
    name,
    category: vegetableNames.has(name)
      ? "vegetable"
      : (categoryMap[folder] ?? "main_dish"),
    serving: {
      amount: 100,
      unit: "克",
      weightG: 100,
      label: "每100克",
    },
    nutrients: values,
    source: {
      type: "third_party",
      publisher: "CookLikeHOC / 溯源报告 2.0 整理",
      title: `${name}开源菜谱与营养成分`,
      url: sourceUrl(relativePath),
      accessedAt: "2026-07-02",
    },
    notes: [
      "门店实际份量未公开",
      "信达好第坊店实时在售状态待核验",
    ],
  });
}

records.sort((left, right) => left.name.localeCompare(right.name, "zh-CN"));

const output = [
  "// Generated by scripts/import-cooklikehoc.mjs. Do not edit by hand.",
  `export const reportFoods = Object.freeze(${JSON.stringify(records, null, 2)});`,
  "",
].join("\n");

await writeFile(outputPath, output, "utf8");
console.log(`Imported ${records.length} complete nutrition records into ${outputPath}.`);
